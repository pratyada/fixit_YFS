export function getPlanById(id) {
  return WORKOUT_PLANS.find(p => p.id === id);
}

export function getTodayWorkout(plan) {
  if (!plan) return null;
  // Get day of week (Mon=1, Sun=7) and map to plan schedule
  const dayOfWeek = new Date().getDay(); // 0=Sun, 1=Mon, ..., 6=Sat
  // Map to training days: Mon=day1, Tue=day2, etc. Rest on weekends for 5-day plans
  if (dayOfWeek === 0 || dayOfWeek === 6) {
    // Weekend — rest day for 5-day plans, day 3 for 3-day plans (Sat only)
    if (plan.daysPerWeek === 3 && dayOfWeek === 6) {
      return plan.schedule[2]; // Saturday = day 3
    }
    return null; // Rest day
  }
  const dayIndex = Math.min(dayOfWeek - 1, plan.schedule.length - 1);
  return plan.schedule[dayIndex] || null;
}
